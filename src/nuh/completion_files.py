"""Where nuh's zsh completion file (``_nuh``) lives, and whether nuh wrote one.

``nuh install`` writes it into oh-my-zsh's completions directory when there
is one (``$ZSH_CACHE_DIR/completions``, which oh-my-zsh creates and puts on
``fpath``), else into ``${XDG_DATA_HOME:-~/.local/share}/zsh/site-functions``.
``completion_install`` writes and removes it; the CLI's first-run hint
(``completion_hint``) looks for it. Both share these paths, and this module
only reads the environment and stats files, so the hint stays cheap.
"""

from __future__ import annotations

import os
import re
from pathlib import Path

NAME = "_nuh"

# The second line ``completion_zsh.render`` writes. A file without it is not nuh's: nothing overwrites or deletes it.
_GENERATED = re.compile(r"^# zsh completion for nuh \S+, generated by ", re.MULTILINE)
_HEAD_BYTES = 512


def site_functions() -> Path:
    """``${XDG_DATA_HOME:-~/.local/share}/zsh/site-functions``: the directory used when there is no oh-my-zsh."""
    data_home = os.environ.get("XDG_DATA_HOME") or os.path.join(Path.home(), ".local", "share")
    return Path(data_home) / "zsh" / "site-functions"


def oh_my_zsh_dirs(cache_dir: str | None) -> list[Path]:
    """oh-my-zsh's possible completions directories, in order of preference, whether or not they exist.

    *cache_dir* is ``ZSH_CACHE_DIR`` (asked of an interactive zsh, or from the
    environment); then ``$ZSH/cache`` and the default ``~/.oh-my-zsh/cache``.
    """
    caches = [cache_dir, os.path.join(os.environ["ZSH"], "cache") if os.environ.get("ZSH") else None,
              os.path.join(Path.home(), ".oh-my-zsh", "cache")]
    result: list[Path] = []
    for cache in caches:
        if cache and (Path(cache) / "completions") not in result:
            result.append(Path(cache) / "completions")
    return result


def target(cache_dir: str | None) -> Path:
    """Where ``nuh install`` writes ``_nuh``: the first oh-my-zsh completions directory found, else site-functions."""
    for directory in oh_my_zsh_dirs(cache_dir):
        if directory.is_dir():
            return directory / NAME
    return site_functions() / NAME


def candidates(cache_dir: str | None) -> list[Path]:
    """Every ``_nuh`` path nuh may have written, whether or not it exists."""
    return [directory / NAME for directory in [*oh_my_zsh_dirs(cache_dir), site_functions()]]


def nuh_written(path: Path) -> bool:
    """True when *path* is a file nuh generated (its header line), False for a missing or foreign file."""
    try:
        with open(path, "rb") as f:
            head = f.read(_HEAD_BYTES)
    except OSError:
        # Missing, a directory or unreadable: not a file nuh can vouch for having
        # written, so callers neither replace nor delete it.
        return False
    return bool(_GENERATED.search(head.decode("utf-8", errors="replace")))


def written(cache_dir: str | None) -> list[Path]:
    """The ``_nuh`` files nuh wrote that exist now."""
    return [path for path in candidates(cache_dir) if nuh_written(path)]
